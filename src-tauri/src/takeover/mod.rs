//!    否则一次接管就会毁掉用户的 MCP 配置、权限设置、快捷键绑定。
//! 2. **解析失败即中止，绝不从空文档重建**。宁可接管失败让用户看到报错，
//!    也不能把配置文件写没。
//!
//! 还原靠的是「首次写入前的字节级备份」，而不是"反向推导原值"。后者在用户
//! 中途手动改过配置时必然出错。

